import { afterAll, beforeAll, describe, expect, mock, test } from "bun:test"
import { chmod, mkdtemp, rm, writeFile } from "node:fs/promises"
import { tmpdir } from "node:os"
import { join } from "node:path"

type Part = { type: string; id?: string; delta?: string; error?: unknown }
type Call = { providerOptions?: Record<string, Record<string, unknown>> }
type Model = {
  modelId: string
  doStream: (options: Call) => Promise<{ stream: ReadableStream<Part> }>
  doGenerate: (options: Call) => Promise<{ text: string }>
}
type Provider = ((modelId: string, settings?: Record<string, unknown>) => Model) & {
  languageModel: (modelId: string, settings?: Record<string, unknown>) => Model
}
type Wrapper = {
  notConnected: string
  withCliDir: (settings?: Record<string, unknown>, env?: Record<string, string>) => Record<string, unknown>
  delegatePlan: (
    headers: Record<string, string>,
    env: Record<string, string>,
  ) => { env: Record<string, string> } | undefined
  createSubscription: (options: Record<string, unknown>, factory: unknown) => Provider
}

const authError = (message: string) => Object.assign(new Error(message), { auth: true })

mock.module("ai-sdk-provider-claude-code", () => ({
  createClaudeCode: () => {
    throw new Error("the bundled factory is not used in tests")
  },
  createAuthenticationError: (input: { message: string }) => authError(input.message),
  isAuthenticationError: (error: { auth?: boolean }) => error?.auth === true,
}))

const ask = ["AskUserQuestion", "Agent", "Task"]

const source = join(import.meta.dir, "../../resources/provider/subscription.mjs")
const wrapper = (await import(source)) as Wrapper

const fake = (parts: Part[] = [], failure?: Error) => {
  const calls: Array<{ modelId: string; settings: Record<string, unknown> | undefined }> = []
  const factories: unknown[] = []
  const factory = (input: unknown) => {
    factories.push(input)
    return {
      languageModel: (modelId: string, settings?: Record<string, unknown>): Model => {
        calls.push({ modelId, settings })
        return {
          modelId,
          doStream: async () => {
            if (failure) throw failure
            return { stream: new ReadableStream({ start: (c) => (parts.forEach((p) => c.enqueue(p)), c.close()) }) }
          },
          doGenerate: async () => {
            if (failure) throw failure
            return { text: `generated by ${modelId}` }
          },
        }
      },
    }
  }
  return { calls, factories, factory }
}

const drain = async (stream: ReadableStream<Part>) => Array.fromAsync(stream)

let dir = ""

beforeAll(async () => {
  dir = await mkdtemp(join(tmpdir(), "subscription-wrapper-"))
  await writeFile(join(dir, "signed-out"), "#!/bin/sh\necho '{\"loggedIn\": false}'\n")
  await chmod(join(dir, "signed-out"), 0o755)
})

afterAll(async () => {
  await rm(dir, { recursive: true, force: true })
})

describe("subscription wrapper effort", () => {
  test("builds the model of a call with the effort of its variant", async () => {
    const model = fake([{ type: "finish" }])
    const provider = wrapper.createSubscription(
      { defaultSettings: { permissionMode: "bypassPermissions" } },
      model.factory,
    )

    const stream = await provider.languageModel("sonnet", { maxTurns: 2 }).doStream({
      providerOptions: { subscription: { effort: "high" } },
    })

    expect(await drain(stream.stream)).toEqual([{ type: "finish" }])
    expect(model.factories).toEqual([{ defaultSettings: { permissionMode: "bypassPermissions" } }])
    expect(model.calls.at(-1)).toEqual({ modelId: "sonnet", settings: { maxTurns: 2, effort: "high", disallowedTools: ask } })
  })

  test("passes the effort to generate calls too", async () => {
    const model = fake()
    const provider = wrapper.createSubscription({}, model.factory)

    expect(await provider("opus").doGenerate({ providerOptions: { subscription: { effort: "max" } } })).toEqual({
      text: "generated by opus",
    })
    expect(model.calls.at(-1)).toEqual({ modelId: "opus", settings: { effort: "max", disallowedTools: ask } })
  })

  test("keeps the settings of the model when the call has no effort", async () => {
    const model = fake()
    const provider = wrapper.createSubscription({}, model.factory)

    await provider.languageModel("haiku", { maxTurns: 1 }).doGenerate({ providerOptions: { subscription: {} } })
    await provider.languageModel("haiku").doGenerate({})

    expect(model.calls).toEqual([
      { modelId: "haiku", settings: { maxTurns: 1, disallowedTools: ask } },
      { modelId: "haiku", settings: { maxTurns: 1, disallowedTools: ask } },
      { modelId: "haiku", settings: { disallowedTools: ask } },
      { modelId: "haiku", settings: { disallowedTools: ask } },
    ])
  })

  test("reads the effort under the provider id the host passes as name", async () => {
    const model = fake()
    const provider = wrapper.createSubscription({ name: "second" }, model.factory)

    await provider("sonnet").doGenerate({
      providerOptions: { subscription: { effort: "low" }, second: { effort: "max" } },
    })
    await provider("opus").doGenerate({ providerOptions: { subscription: { effort: "low" } } })

    expect(model.calls.filter((call) => (call.settings as { effort?: string }).effort)).toEqual([
      { modelId: "sonnet", settings: { effort: "max", disallowedTools: ask } },
    ])
  })

  test("exposes the properties of the model", () => {
    const provider = wrapper.createSubscription({}, fake().factory)

    expect(provider.chat("sonnet").modelId).toBe("sonnet")
  })
})

describe("subscription wrapper delegate tool", () => {
  const headers = {
    "x-opencode-session-id": "ses_parent",
    "x-void-delegate-url": "http://127.0.0.1:4100/",
    "x-void-delegate-directory": "%2Fwork%2Fmy%20project",
  }

  test("adds the delegate server with the parent id and allows its tool", async () => {
    process.env.OPENCODE_SERVER_PASSWORD = "secret"
    const model = fake()
    const provider = wrapper.createSubscription({}, model.factory)

    await provider("sonnet").doGenerate({ headers })

    const settings = model.calls.at(-1)!.settings as {
      mcpServers: { delegate: { type: string; command: string; args: string[]; env: Record<string, string> } }
      allowedTools: string[]
    }
    expect(settings.allowedTools).toEqual(["mcp__delegate__delegate"])
    expect(settings.mcpServers.delegate.type).toBe("stdio")
    expect(settings.mcpServers.delegate.args[0]).toEndWith("delegate/mcp.mjs")
    expect(settings.mcpServers.delegate.env).toMatchObject({
      VOID_DELEGATE_URL: "http://127.0.0.1:4100/",
      VOID_DELEGATE_PARENT: "ses_parent",
      VOID_DELEGATE_DIRECTORY: "/work/my project",
      VOID_DELEGATE_PASSWORD: "secret",
    })
  })

  test("merges with the servers and tools of the defaults and of the model", async () => {
    const model = fake()
    const provider = wrapper.createSubscription(
      {
        defaultSettings: {
          mcpServers: { hub: { command: "hub" } },
          allowedTools: ["Read", "mcp__delegate__delegate"],
        },
      },
      model.factory,
    )

    await provider("opus", { mcpServers: { extra: { command: "extra" } }, allowedTools: ["Grep"] }).doGenerate({
      headers,
      providerOptions: { subscription: { effort: "high" } },
    })

    const settings = model.calls.at(-1)!.settings as {
      mcpServers: Record<string, unknown>
      allowedTools: string[]
      effort: string
    }
    expect(Object.keys(settings.mcpServers).sort()).toEqual(["delegate", "extra", "hub"])
    expect(settings.allowedTools).toEqual(["Read", "mcp__delegate__delegate", "Grep"])
    expect(settings.effort).toBe("high")
  })

  test("adds nothing without a session id or a server url", async () => {
    const model = fake()
    const provider = wrapper.createSubscription({}, model.factory)

    await provider("sonnet").doGenerate({ headers: { "x-void-delegate-url": "http://127.0.0.1:4100/" } })
    await provider("sonnet").doGenerate({ headers: { "x-opencode-session-id": "ses_parent" } })
    await provider("sonnet").doGenerate({})

    expect(model.calls.every((call) => !(call.settings as { mcpServers?: unknown }).mcpServers)).toBe(true)
  })

  test("blocks the ask tool in every model and merges configured disallowed tools without duplicates", async () => {
    const model = fake()
    const provider = wrapper.createSubscription(
      { defaultSettings: { disallowedTools: ["WebSearch", "AskUserQuestion"] } },
      model.factory,
    )

    await provider("opus", { disallowedTools: ["Bash", "WebSearch"] }).doGenerate({ headers })
    await provider("opus").doGenerate({})

    expect([model.calls[1]!, model.calls[3]!].map((call) => (call.settings as { disallowedTools: string[] }).disallowedTools)).toEqual([
      ["WebSearch", "AskUserQuestion", "Bash", "Agent", "Task"],
      ["WebSearch", "AskUserQuestion", "Agent", "Task"],
    ])
  })

  test("reads the headers case-insensitively", () => {
    const plan = wrapper.delegatePlan({ "X-OpenCode-Session-Id": "ses_parent", "X-Void-Delegate-Url": "http://h/" }, {})

    expect(plan?.env).toMatchObject({ VOID_DELEGATE_PARENT: "ses_parent", VOID_DELEGATE_URL: "http://h/" })
  })
})

describe("subscription wrapper login handling", () => {
  test("drops the login hint of the stream", async () => {
    const provider = wrapper.createSubscription(
      {},
      fake([
        { type: "text-start", id: "a" },
        { type: "text-delta", id: "a", delta: "Not logged in · Please run /login" },
        { type: "text-end", id: "a" },
        { type: "finish" },
      ]).factory,
    )

    const stream = await provider("sonnet").doStream({ providerOptions: { subscription: { effort: "low" } } })

    expect(await drain(stream.stream)).toEqual([{ type: "finish" }])
  })

  test("maps a login failure to the connect message", async () => {
    const provider = wrapper.createSubscription({}, fake([], authError("Not logged in · Please run /login")).factory)

    await expect(provider("sonnet").doGenerate({})).rejects.toThrow(wrapper.notConnected)
  })

  test("stops before the call when the subscription is signed out", async () => {
    const model = fake()
    const provider = wrapper.createSubscription(
      { defaultSettings: { pathToClaudeCodeExecutable: join(dir, "signed-out") } },
      model.factory,
    )

    await expect(
      provider("sonnet").doStream({ providerOptions: { subscription: { effort: "high" } } }),
    ).rejects.toThrow(wrapper.notConnected)
    expect(model.calls.map((call) => call.settings)).not.toContainEqual({ effort: "high" })
  })
})

describe("subscription wrapper login directory", () => {
  test("points the cli at the profile login directory", () => {
    expect(wrapper.withCliDir({ a: 1 }, { VOID_CLI_DIR: "/d" })).toEqual({ a: 1, env: { CLAUDE_CONFIG_DIR: "/d" } })
  })

  test("keeps an explicit login directory and leaves settings alone without one", () => {
    const set = { env: { CLAUDE_CONFIG_DIR: "/x" } }
    expect(wrapper.withCliDir(set, { VOID_CLI_DIR: "/d" })).toBe(set)
    expect(wrapper.withCliDir({ a: 1 }, {})).toEqual({ a: 1 })
  })
})
